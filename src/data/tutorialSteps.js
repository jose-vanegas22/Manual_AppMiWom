export function buildStages(steps) {
  const stages = [];
  steps.forEach((step, index) => {
    const existing = stages.find((s) => s.name === step.stage);
    if (!existing) {
      stages.push({ name: step.stage, firstIndex: index, lastIndex: index, count: 1 });
    } else {
      existing.lastIndex = index;
      existing.count += 1;
    }
  });
  return stages;
}

export const stages = buildStages(tutorialSteps);
